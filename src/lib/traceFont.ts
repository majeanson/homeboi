const FALLBACK_W = 0.55 // advance for an unknown character (drawn blank)
const LETTER_SPACING = 0.16 // extra advance between glyphs, in cap-height units

// Advance width (cap-height units, includes trailing letter-spacing) of one line.
export function measureTrace(text: string): number {
  let w = 0
  for (const ch of text) w += (GLYPHS[ch]?.w ?? FALLBACK_W) + LETTER_SPACING
  return w
}

// Draw one line of monoline text with its LEFT baseline at (x, baseline), cap
// height `cap` px. Caller sets strokeStyle / lineWidth / dash. Returns the x the
// next glyph would start at. Descenders dip below `baseline` (skeleton, not fill).
export function drawTraceLine(ctx: CanvasRenderingContext2D, text: string, x: number, baseline: number, cap: number): number {
  const top = baseline - cap
  let cx = x
  for (const ch of text) {
    const g = GLYPHS[ch]
    if (g) {
      for (const stroke of g.s) {
        ctx.beginPath()
        stroke.forEach(([gx, gy], i) => {
          const px = cx + gx * cap
          const py = top + gy * cap
          i ? ctx.lineTo(px, py) : ctx.moveTo(px, py)
        })
        ctx.stroke()
      }
    }
    cx += ((g?.w ?? FALLBACK_W) + LETTER_SPACING) * cap
  }
  return cx
}

// Greedily wrap `text` into lines whose drawn width fits `maxW` cap-height units,
// breaking on spaces (a single over-long word is kept whole). For multi-row trace.
export function wrapTrace(text: string, maxW: number): string[] {
  const words = text.trim().split(/\s+/).filter(Boolean)
  if (!words.length) return []
  const lines: string[] = []
  let cur = ''
  for (const word of words) {
    const trial = cur ? `${cur} ${word}` : word
    if (cur && measureTrace(trial) > maxW) {
      lines.push(cur)
      cur = word
    } else {
      cur = trial
    }
  }
  if (cur) lines.push(cur)
  return lines
}
